// Helper function to get item by slug
export const getItemBySlug = (slug) => {
  for (const category of Object.values(menuData)) {
    const item = category.find((item) => item.slug === slug);
    if (item) return item;
  }
  return null;
};

// Helper function to get all items with 3D models
export const getItemsWithModels = () => {
  const items = [];
  for (const category of Object.values(menuData)) {
    items.push(...category.filter((item) => item.modelUrl && item.slug));
  }
  return items;
};
